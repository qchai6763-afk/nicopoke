function buildAnimalSets() {
  const kanji = {};
  ANIMAL_KANJI.split(/\s+/)
    .filter(Boolean)
    .forEach((pair) => {
      const [key, list] = pair.split(":");
      if (key && list) kanji[key] = list.split(",");
    });
  const seen = new Set();
  const byKana = {};
  ANIMAL_WORDS.split(/\s+/)
    .filter(Boolean)
    .forEach((word) => {
      if (seen.has(word)) return;
      seen.add(word);
      const first = animalSeion(word.charAt(0));
      (byKana[first] = byKana[first] || []).push({ key: word, ok: [word].concat(kanji[word] || []) });
    });
  return ANIMAL_KANA.map((kana) => ({ kana, items: byKana[kana] || [] }));
}

